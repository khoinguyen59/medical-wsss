        "print(f'[LOSS] Stage 1 criterion={type(criterion).__name__} (LOSS_TYPE={LOSS_TYPE})')\n",
        "\n",
        "def forward_stage1_with_pda(model, images, enable_pda=False, gamma=0.7):\n",
        "    # Forward pass through dilated backbone with src.training.train_stage1.AttentionModule\n",
        "    conv6 = model.forward_backbone(images)  # (B, 4096, 28, 28)\n",
        "    if enable_pda:\n",
