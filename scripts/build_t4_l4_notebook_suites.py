        "    x = model.dropout7(conv6)\n",
        "    x = model.pool(x)\n",
        "    logits = model.fc8(x).view(x.size(0), -1)  # (B, 4) raw un-sigmoided logits\n",
        "    probs = torch.sigmoid(logits)  # (B, 4) probabilities\n",
        "    return logits, probs\n",
