        "\n",
        "from src.training.train_stage1 import (\n",
        "    AsymmetricLoss,\n",
        "    AttentionModule,\n",
        "    build_optimizer_and_scheduler,\n",
        ")\n",
        "\n",
        "# Instantiate model\n",
        "model = WSSSTissueStage1NetCAM(num_classes=4)\n",
        "model = model.to(DEVICE)\n",
        "attention_module = AttentionModule().to(DEVICE)\n",
        "total_params = sum(p.numel() for p in model.parameters())\n",
        "print(f'[MODEL] Stage 1 ResNet38d Net_CAM instantiated: {total_params:,} parameters')\n",
        "\n",
        "# Optimizer with decoupled 10x head LR and Cosine LR schedule\n",
        "MAX_EPOCHS = 3 if DRY_RUN else 15\n",
        "LEARNING_RATE = 1e-4\n",
        "WEIGHT_DECAY = 1e-4\n",
        "LOSS_TYPE = 'asl'  # Options: 'asl' (AsymmetricLoss) or 'soft_margin' (MultiLabelSoftMarginLoss)\n",
        "\n",
        "optimizer, scheduler = build_optimizer_and_scheduler(\n",
        "    model, lr=LEARNING_RATE, weight_decay=WEIGHT_DECAY, epochs=MAX_EPOCHS\n",
        ")\n",
        "scaler = torch.amp.GradScaler('cuda', enabled=(DEVICE.type == 'cuda'))\n",
        "if LOSS_TYPE == 'asl':\n",
        "    criterion = AsymmetricLoss(gamma_neg=4.0, gamma_pos=0.0, clip=0.05)\n",
