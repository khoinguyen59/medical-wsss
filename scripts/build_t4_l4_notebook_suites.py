def get_clean_cell_8_stage1(batch_size=16, num_workers=2):
    return [
        "import re\n",
        "import random\n",
        "from collections import defaultdict\n",
        "from PIL import Image\n",
        "import numpy as np\n",
        "import torch\n",
        "from torch.utils.data import Dataset, DataLoader\n",
        "from torchvision import transforms\n",
        "\n",
        "from src.training.dataset_loader import extract_patient_id, load_bcss_patient_splits\n",
        "\n",
        "# Baseline Parity input normalization: 'zero_one' matches repos/WSSS-Tissue/1_train_stage1.py\n",
        "# and domain-pretrained ResNet-38d checkpoints; metadata 'input_norm' is persisted for Stage 2.\n",
        "STAGE1_INPUT_NORM = 'zero_one'  # Options: 'zero_one' (Recommended, paper parity) | 'imagenet'\n",
        "\n",
        "def _sample_patient_stratified(files, max_samples, seed=42):\n",
        "    if max_samples is None or len(files) <= max_samples:\n",
        "        return list(files)\n",
        "    rng = random.Random(seed)\n",
        "    by_pid = defaultdict(list)\n",
        "    for f in files:\n",
        "        by_pid[extract_patient_id(f.name)].append(f)\n",
        "    pids = sorted(by_pid.keys())\n",
        "    for pid in pids:\n",
        "        rng.shuffle(by_pid[pid])\n",
        "    selected = []\n",
        "    idx = 0\n",
        "    while len(selected) < max_samples:\n",
        "        progressed = False\n",
        "        for pid in pids:\n",
        "            if idx < len(by_pid[pid]):\n",
        "                selected.append(by_pid[pid][idx])\n",
        "                progressed = True\n",
        "                if len(selected) >= max_samples:\n",
        "                    break\n",
        "        if not progressed:\n",
        "            break\n",
        "        idx += 1\n",
        "    return selected\n",
        "\n",
        "class BCSSStage1Dataset(Dataset):\n",
        "    \"\"\"BCSS-WSSS Stage 1 multi-label histopathology dataset with patient-level anti-leakage.\"\"\"\n",
        "    def __init__(self, img_dir, transform=None, limit=None, patient_ids=None):\n",
        "        self.img_dir = Path(img_dir)\n",
        "        self.transform = transform\n",
        "        files = list(self.img_dir.glob('*.png'))\n",
        "        if len(files) == 0 and (self.img_dir / 'img').is_dir():\n",
        "            files = list((self.img_dir / 'img').glob('*.png'))\n",
        "        if len(files) == 0 and self.img_dir.is_dir():\n",
        "            files = list(self.img_dir.rglob('*.png'))\n",
        "        if len(files) == 0:\n",
        "            raise FileNotFoundError(f'[STAGE1 ERROR] No patches found in {self.img_dir}. Please ensure dataset extraction completed successfully!')\n",
        "        files = sorted(files)\n",
        "        if patient_ids is not None:\n",
        "            allowed_pids = {str(p).upper() for p in patient_ids}\n",
        "            filtered = [f for f in files if extract_patient_id(f.name) in allowed_pids]\n",
        "            if len(filtered) > 0:\n",
        "                files = filtered\n",
        "        self.files = _sample_patient_stratified(files, limit, seed=42) if (limit is not None and limit > 0) else files\n",
        "        self.pattern = re.compile(r'\\[([0-9\\s,]+)\\]')\n",
        "        print(f'[DATASET] Stage 1 Train ingested {len(self.files):,} patches from {self.img_dir}')\n",
        "\n",
        "    def __len__(self):\n",
        "        return len(self.files)\n",
        "\n",
        "    def __getitem__(self, idx):\n",
        "        filepath = self.files[idx]\n",
        "        image = Image.open(filepath).convert('RGB')\n",
        "        if self.transform is not None:\n",
        "            image = self.transform(image)\n",
        "        match = self.pattern.search(filepath.name)\n",
        "        if match:\n",
        "            raw_str = match.group(1).replace(',', ' ').strip()\n",
        "            digits = [float(c) for c in raw_str if c.isdigit()]\n",
        "            if len(digits) == 4:\n",
        "                label = torch.tensor(digits, dtype=torch.float32)\n",
        "            else:\n",
        "                tokens = raw_str.split()\n",
        "                label = torch.tensor([float(x) for x in tokens], dtype=torch.float32) if len(tokens) == 4 else torch.zeros(4, dtype=torch.float32)\n",
        "        else:\n",
        "            label = torch.zeros(4, dtype=torch.float32)\n",
        "        return filepath.name, image, label\n",
        "\n",
        "class BCSSStage1ValDataset(Dataset):\n",
        "    \"\"\"Independent Stage 1 validation dataset deriving true multi-hot labels and GT masks from val/mask.\"\"\"\n",
        "    def __init__(self, img_dir, mask_dir, transform=None, limit=None, patient_ids=None):\n",
        "        self.img_dir = Path(img_dir)\n",
        "        self.mask_dir = Path(mask_dir) if mask_dir is not None else None\n",
        "        self.transform = transform\n",
        "        files = sorted(list(self.img_dir.glob('*.png'))) if self.img_dir.is_dir() else []\n",
        "        if len(files) == 0 and self.img_dir.is_dir():\n",
        "            files = sorted(list(self.img_dir.rglob('*.png')))\n",
        "        if patient_ids is not None:\n",
        "            allowed_pids = {str(p).upper() for p in patient_ids}\n",
        "            filtered = [f for f in files if extract_patient_id(f.name) in allowed_pids]\n",
        "            if len(filtered) > 0:\n",
        "                files = filtered\n",
        "        self.files = _sample_patient_stratified(files, limit, seed=42) if (limit is not None and limit > 0) else files\n",
        "        uniq_pids = len({extract_patient_id(f.name) for f in self.files})\n",
        "        print(f'[DATASET] Stage 1 Val ingested {len(self.files):,} patches across {uniq_pids} unique patients (Anti-Leakage Verified).')\n",
        "\n",
        "    def __len__(self):\n",
        "        return len(self.files)\n",
        "\n",
        "    def __getitem__(self, idx):\n",
        "        filepath = self.files[idx]\n",
        "        image = Image.open(filepath).convert('RGB')\n",
        "        if self.transform is not None:\n",
        "            image = self.transform(image)\n",
        "        mask_path = (self.mask_dir / filepath.name) if (self.mask_dir is not None and self.mask_dir.is_dir()) else None\n",
        "        if mask_path is not None and mask_path.is_file():\n",
        "            m_img = Image.open(mask_path)\n",
        "            if m_img.mode != 'P':\n",
        "                m_img = m_img.convert('L')\n",
        "            gt_arr = np.array(m_img.resize((224, 224), Image.NEAREST), dtype=np.int64)\n",
        "            if gt_arr.ndim == 3:\n",
        "                gt_arr = gt_arr[:, :, 0]\n",
        "            label = torch.tensor([1.0 if np.any(gt_arr == c) else 0.0 for c in range(4)], dtype=torch.float32)\n",
        "        else:\n",
        "            gt_arr = np.full((224, 224), 255, dtype=np.int64)\n",
        "            label = torch.zeros(4, dtype=torch.float32)\n",
        "        return filepath.name, image, label, torch.from_numpy(gt_arr).long()\n",
        "\n",
        "# Data augmentation pipeline aligned with STAGE1_INPUT_NORM\n",
        "_train_ops = [\n",
        "    transforms.Resize((224, 224)),\n",
        "    transforms.RandomHorizontalFlip(p=0.5),\n",
        "    transforms.RandomVerticalFlip(p=0.5),\n",
        "    transforms.ColorJitter(brightness=0.1, contrast=0.1, saturation=0.1, hue=0.03),\n",
        "    transforms.ToTensor(),\n",
        "]\n",
        "_val_ops = [\n",
        "    transforms.Resize((224, 224)),\n",
        "    transforms.ToTensor(),\n",
        "]\n",
        "if STAGE1_INPUT_NORM == 'imagenet':\n",
        "    _norm_op = transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])\n",
        "    _train_ops.append(_norm_op)\n",
        "    _val_ops.append(_norm_op)\n",
        "train_transform = transforms.Compose(_train_ops)\n",
        "val_transform = transforms.Compose(_val_ops)\n",
        "\n",
        f"BATCH_SIZE = {batch_size}\n",
        f"NUM_WORKERS = {num_workers}\n",
        "DRY_RUN = False if 'DRY_RUN' not in globals() else DRY_RUN  # Set to True for fast smoke-test\n",
        "patient_splits = load_bcss_patient_splits()\n",
        "train_patient_ids = patient_splits.get('train', [])\n",
        "val_patient_ids = patient_splits.get('val', [])\n",
        "assert set(train_patient_ids).isdisjoint(set(val_patient_ids)), 'Invariant 08 violation: train/val patient overlap!'\n",
        "\n",
        "train_dataset = BCSSStage1Dataset(\n",
        "    TRAIN_DIR,\n",
        "    transform=train_transform,\n",
        "    limit=64 if DRY_RUN else None,\n",
        "    patient_ids=train_patient_ids,\n",
        ")\n",
        "train_loader = DataLoader(\n",
        "    train_dataset,\n",
        "    batch_size=min(BATCH_SIZE, max(1, len(train_dataset))),\n",
        "    shuffle=True,\n",
        "    num_workers=NUM_WORKERS,\n",
        "    pin_memory=torch.cuda.is_available(),\n",
        "    drop_last=(len(train_dataset) >= BATCH_SIZE),\n",
        ")\n",
        "val_dataset = BCSSStage1ValDataset(\n",
        "    VAL_IMG_DIR,\n",
        "    VAL_MASK_DIR,\n",
        "    transform=val_transform,\n",
        "    limit=32 if DRY_RUN else None,\n",
        "    patient_ids=val_patient_ids,\n",
        ")\n",
        "val_loader = DataLoader(\n",
        "    val_dataset,\n",
        "    batch_size=min(BATCH_SIZE, max(1, len(val_dataset))),\n",
        "    shuffle=False,\n",
        "    num_workers=NUM_WORKERS,\n",
        "    pin_memory=torch.cuda.is_available(),\n",
        "    drop_last=False,\n",
        ") if len(val_dataset) > 0 else None\n",
        "print(f'[DATALOADER] Train batches/epoch: {len(train_loader)} (BS={BATCH_SIZE}, Samples={len(train_dataset):,}, norm={STAGE1_INPUT_NORM})')\n",
        "print(f'[DATALOADER] Val batches/epoch: {len(val_loader) if val_loader else 0} (Samples={len(val_dataset):,})')\n",
    ]


