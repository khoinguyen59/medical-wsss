        "        fp = np.sum(cm[:, c]) - tp\n",
        "        fn = np.sum(cm[c, :]) - tp\n",
        "        denom_iou = tp + fp + fn\n",
        "        iou = (tp / denom_iou * 100.0) if denom_iou > 0 else 0.0\n",
