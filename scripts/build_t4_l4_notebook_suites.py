        "            grad_y = cv2.Sobel(gray_guide, cv2.CV_32F, 0, 1, ksize=3)\n",
        "            edge_weight = np.clip(1.0 - np.sqrt(grad_x**2 + grad_y**2), 0.5, 1.0)\n",
